/**
 * Render the Caddyfile for a domain: static app + same-origin blind relay
 * to the T3 node. Security headers are taken from the build's `dist/_headers`
 * (the same CSP / COOP / COEP the Vite build computed), so there is one
 * source of truth.
 *
 *   node deploy/render-caddyfile.mjs <domain> <webroot> [t3-upstream] > /etc/caddy/Caddyfile
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

const [domain, webroot, upstream = "https://cn-api.sg.testnet.t3n.terminal3.io"] = process.argv.slice(2);
if (!domain || !webroot) {
  console.error("usage: node deploy/render-caddyfile.mjs <domain> <webroot> [t3-upstream]");
  process.exit(2);
}
const upstreamHost = new URL(upstream).host;

const headers = readFileSync(join(webroot, "_headers"), "utf8")
  .split("\n")
  .filter((l) => /^\s+[A-Za-z-]+:/.test(l))
  .map((l) => {
    const i = l.indexOf(":");
    return `\t\t\t${l.slice(0, i).trim()} "${l.slice(i + 1).trim().replace(/"/g, '\\"')}"`;
  })
  .join("\n");

process.stdout.write(`# Generated by deploy/render-caddyfile.mjs — do not edit by hand.
{
\t# No access logs: the relay never needs to record who submitted what.
\tlog default {
\t\toutput discard
\t}
}

${domain} {
\t# ── Blind relay to the T3 node ─────────────────────────────────────
\t# The browser encrypts the submission to the attested enclave (ML-KEM
\t# session set up by @terminal3/t3n-sdk after verifying the node's TDX
\t# attestation) before it leaves the device. This relay terminates TLS but
\t# only ever sees that ciphertext. Same origin ⇒ no CORS, first-party cookies.
\thandle_path /t3/* {
\t\treverse_proxy ${upstream} {
\t\t\theader_up Host ${upstreamHost}
\t\t\theader_up -Origin
\t\t\theader_up -Referer
\t\t\theader_down -Access-Control-Allow-Origin
\t\t\theader_down -Access-Control-Allow-Credentials
\t\t}
\t}

\t# Expire the relayed T3 session cookie (HttpOnly) so each seal starts a
\t# fresh sign-in — see clearT3Session() in the app.
\thandle /pde-signout {
\t\theader Set-Cookie "t3_session=; Max-Age=0; HttpOnly; Secure; SameSite=Lax; Path=/"
\t\theader Cache-Control no-store
\t\trespond 204
\t}

\t# ── The capture app (static) ───────────────────────────────────────
\thandle {
\t\troot * ${webroot}
\t\theader {
${headers}
\t\t\t-Server
\t\t}
\t\t@hashed path /assets/*
\t\theader @hashed Cache-Control "public, max-age=31536000, immutable"
\t\t@fresh path / /index.html /sw.js /version.json /pde.config.json /models/manifest.json /manifest.webmanifest
\t\theader @fresh Cache-Control "no-cache"
\t\t@manifest path *.webmanifest
\t\theader @manifest Content-Type "application/manifest+json"
\t\t@onnx path *.onnx
\t\theader @onnx Content-Type "application/octet-stream"
\t\t@meta path /_headers /assets-index.json
\t\theader @meta Content-Type "text/plain; charset=utf-8"
\t\t# Compress on the fly, including WASM and ONNX (not in Caddy's default
\t\t# list): the 26 MB ONNX Runtime WASM goes out as ~6 MB. Assets are
\t\t# immutable and cached by the browser + service worker, so this happens
\t\t# about once per device. (file_server's \`precompressed\` answers 206
\t\t# without a Range request in Caddy 2.10, which breaks module scripts.)
\t\tencode zstd gzip {
\t\t\tminimum_length 1024
\t\t\tmatch {
\t\t\t\theader Content-Type text/*
\t\t\t\theader Content-Type application/javascript*
\t\t\t\theader Content-Type application/json*
\t\t\t\theader Content-Type application/manifest+json*
\t\t\t\theader Content-Type application/wasm*
\t\t\t\theader Content-Type application/octet-stream*
\t\t\t\theader Content-Type image/svg+xml*
\t\t\t}
\t\t}
\t\tfile_server
\t}
}
`);
