/**
 * Write the capture app's deployment config. The app talks to T3 through the
 * same-origin relay at https://<domain>/t3 (see deploy/).
 *
 * By default each user's data goes to their OWN vault: after the email
 * sign-in the app seals to `z:<their tid>:doc-intake`, which they registered
 * under their DID (starter/ → setup-vault). No key or contract of ours is
 * involved, so this needs no `pnpm t3:deploy` and holds nothing secret.
 * PDE_FIXED_CONTRACT=1 instead sends everyone to the contract from the last
 * `pnpm t3:deploy` (the earlier, shared-contract setup).
 *
 *   pnpm t3:config -- capture.example.com
 *   → deploy/out/pde.config.json   (build with PDE_CONFIG_FILE=deploy/out/pde.config.json)
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { networkEnv, onFailure, readDeployment } from "./common.ts";

process.on("unhandledRejection", onFailure);

// A domain gives an absolute relay URL; no argument gives "/t3", the relay on
// whatever origin serves the app (Vercel: set the output as PDE_CONFIG_JSON).
const domain = process.argv.slice(2).find((a) => a !== "--");
if (domain && !/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(domain)) {
  console.error("usage: pnpm t3:config -- [capture-domain]   e.g. capture.example.com (omit for a relative /t3)");
  process.exit(2);
}
const relay = domain ? `https://${domain}/t3` : "/t3";
const fixed = process.env.PDE_FIXED_CONTRACT === "1" ? await readDeployment() : null;
const environment = fixed?.environment ?? networkEnv();
const base = JSON.parse(await readFile(new URL("../../apps/capture-pwa/public/pde.config.json", import.meta.url), "utf8"));
const config = {
  ...base,
  $comment: fixed
    ? `Generated by pnpm t3:config (${relay}) from ${fixed.contract} v${fixed.version} (${environment}).`
    : `Generated by pnpm t3:config (${relay}, ${environment}): each user's own vault, z:<their tid>:doc-intake.`,
  destination: {
    type: "t3n",
    baseUrl: relay,
    environment,
    target: fixed
      ? { kind: "contract", contractId: fixed.contract, functionName: "ingest" }
      : { kind: "own-contract", tail: "doc-intake", functionName: "ingest" },
    // Email one-time code: what real end users have. Add "wallet" to also offer
    // browser-wallet sign-in (same DID as an ETH key / API key).
    signIn: (process.env.PDE_SIGN_IN ?? "email").split(",").map((m) => m.trim()),
  },
};
const out = new URL("../../deploy/out/pde.config.json", import.meta.url);
await mkdir(new URL("./", out), { recursive: true });
await writeFile(out, JSON.stringify(config, null, 2) + "\n");
console.log(`wrote deploy/out/pde.config.json → ${fixed ? fixed.contract : "each user's own z:<tid>:doc-intake"} via ${relay}`);
if (!domain) console.log(`\nFor Vercel, set this environment variable (Production + Preview):\n\nPDE_CONFIG_JSON=${JSON.stringify(config)}\n`);
